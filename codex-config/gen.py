#!/usr/bin/env python3
"""Translate the Claude Code config in ../claude-config into Codex's formats.

Source of truth stays in claude-config/.  Everything this writes lands in
codex-config/generated/ and is installed into $CODEX_HOME by install.sh,
so a regenerate-and-reinstall is always safe to repeat.

Three translations, because Codex and CC agree on skills but not on the rest:

  claude-config/commands/<n>.md  ->  generated/skills/<n>/SKILL.md
      Codex has no slash-command concept; skills are its invocable unit.
  claude-config/agents/<n>.md    ->  generated/agents/<n>.toml
      Codex subagents are TOML: name / description / developer_instructions.
      `tools:` and `model:` have no Codex equivalent and are dropped (noted
      in the generated header so the loss is visible).
  claude-config/agent-rules/      ->  generated/AGENTS.md      (Codex)
                                      generated/agy/AGENTS.md  (Antigravity)
      Each tool's rule file is the shared kernel and seats plus that tool's
      own harness file and its model family's file (see COMPOSE). Neither
      tool supports CC's `@file` imports, so the parts are joined into one
      file. HTML comments are notes for the human and are stripped.

Skills themselves are not copied -- install.sh symlinks them, so editing a
SKILL.md once serves both agents.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CC = os.path.join(ROOT, "claude-config")
OUT = os.path.join(HERE, "generated")

BANNER = "<!-- generated by codex-config/gen.py from {src} -- edit the source, not this file -->"

RULES = os.path.join(CC, "agent-rules")

# What each tool's global rule file is built from, relative to agent-rules/.
# The kernel and the seats are shared; the harness file and the model file
# are the tool's own. A new tool is one more entry here.
COMPOSE = {
    "codex": ["kernel.md", "seats/lead.md", "seats/thinker.md", "seats/worker.md",
              "harness/codex.md", "models/gpt-family.md"],
    "agy": ["kernel.md", "seats/lead.md", "seats/thinker.md", "seats/worker.md",
            "harness/agy.md", "models/gemini-family.md"],
}
OUTPUT = {"codex": "AGENTS.md", "agy": os.path.join("agy", "AGENTS.md")}

# Names a tool loads on its own when it finds them in a directory. On a
# case-insensitive disk `claude.md` IS `CLAUDE.md`, so a rule source with one
# of these names gets loaded twice, or by the wrong tool.
RESERVED = {"claude.md", "agents.md", "gemini.md"}


def rule_text(rel):
    """One rule file, without the HTML comments that hold notes for the human."""
    with open(os.path.join(RULES, rel), encoding="utf-8") as fh:
        return re.sub(r"<!--.*?-->\n?", "", fh.read(), flags=re.S).strip()


def subagent_rules():
    """agent-type -> rule files, from agent-rules/subagents.map."""
    path = os.path.join(RULES, "subagents.map")
    out = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                parts = line.split("#", 1)[0].split()
                if len(parts) >= 2:
                    out[parts[0]] = parts[1:]
    return out


def reserved_names():
    hits = []
    for root, _dirs, files in os.walk(RULES):
        hits += [os.path.join(root, f) for f in files if f.lower() in RESERVED]
    return hits


def frontmatter(text):
    """Split a CC markdown file into (dict, body). No frontmatter -> ({}, text)."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end == -1:
        return {}, text
    head, body = text[4:end], text[end + 5:]
    meta, key = {}, None
    for line in head.split("\n"):
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):\s?(.*)$", line)
        if m:
            key = m.group(1)
            meta[key] = m.group(2).strip()
        elif key and line.startswith((" ", "\t")):
            meta[key] += " " + line.strip()
    return meta, body.lstrip("\n")


def toml_str(s):
    """Emit a TOML string: triple-quoted for multi-line, escaped single otherwise."""
    if "\n" in s:
        body = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        return '"""\n' + body + '\n"""'
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old == text:
        return "unchanged"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return "written" if old is None else "updated"


def gen_command_skills():
    """Each CC command becomes a one-skill directory."""
    src = os.path.join(CC, "commands")
    results = []
    for name in sorted(os.listdir(src)):
        if not name.endswith(".md"):
            continue
        slug = name[:-3]
        with open(os.path.join(src, name), encoding="utf-8") as fh:
            meta, body = frontmatter(fh.read())
        desc = meta.get("description") or ""
        if not desc:
            # Commands with no frontmatter (e.g. clip.md) are a bare
            # instruction; its first sentence is the only description there is.
            first = body.strip().split("\n")[0]
            desc = (first[:300] + "...") if len(first) > 300 else first
        # Codex surfaces skills by description alone -- say the trigger out
        # loud, since there is no `/name` to type.
        desc = f"{desc.rstrip('.')}. Invoke when the user types /{slug} or asks for it by name."
        text = (
            "---\n"
            f"name: {slug}\n"
            f"description: {desc}\n"
            "---\n\n"
            + BANNER.format(src=f"claude-config/commands/{name}")
            + "\n\n"
            + body.rstrip()
            + "\n"
        )
        results.append((slug, write(os.path.join(OUT, "skills", slug, "SKILL.md"), text)))
    return results


def gen_agents():
    src = os.path.join(CC, "agents")
    extra = subagent_rules()
    results = []
    for name in sorted(os.listdir(src)):
        if not name.endswith(".md"):
            continue
        slug = name[:-3]
        with open(os.path.join(src, name), encoding="utf-8") as fh:
            meta, body = frontmatter(fh.read())
        dropped = [k for k in ("tools", "model") if meta.get(k)]
        # Claude Code hands a subagent its rule files through a hook. Codex has
        # no such hook wired, so the same files are appended to the definition.
        rules = [r for r in extra.get(meta.get("name", slug), [])
                 if os.path.exists(os.path.join(RULES, r))]
        if rules:
            body = body.rstrip() + "\n\n" + "\n\n".join(rule_text(r) for r in rules)
        header = (
            f"# generated by codex-config/gen.py from claude-config/agents/{name}\n"
            "# edit the source, not this file\n"
        )
        if dropped:
            header += "# dropped (no Codex equivalent): " + ", ".join(
                f"{k} = {meta[k]}" for k in dropped) + "\n"
        text = (
            header
            + f"name = {toml_str(meta.get('name', slug))}\n"
            + f"description = {toml_str(meta.get('description', ''))}\n"
            + f"developer_instructions = {toml_str(body.rstrip())}\n"
        )
        results.append((slug, write(os.path.join(OUT, "agents", slug + ".toml"), text)))
    return results


def gen_rules(tool):
    """Join one tool's rule files into the single file that tool reads."""
    parts = COMPOSE[tool]
    missing = [p for p in parts if not os.path.exists(os.path.join(RULES, p))]
    if missing:
        return "skipped", missing
    text = (
        BANNER.format(src="claude-config/agent-rules/: " + ", ".join(parts))
        + "\n\n" + "\n\n".join(rule_text(p) for p in parts) + "\n"
    )
    return write(os.path.join(OUT, OUTPUT[tool]), text), missing


def main():
    print("commands -> skills:")
    for slug, state in gen_command_skills():
        print(f"  {state:9} {slug}")
    print("agents -> toml:")
    for slug, state in gen_agents():
        print(f"  {state:9} {slug}")
    failed = 0
    reserved = reserved_names()
    if reserved:
        print("ERROR rule files with a name a tool auto-loads:", ", ".join(reserved))
        failed = 1
    for tool in COMPOSE:
        state, missing = gen_rules(tool)
        print(f"{OUTPUT[tool]} ({tool}): {state}")
        if missing:
            print("  ERROR missing rule files:", ", ".join(missing))
            failed = 1
    return failed


if __name__ == "__main__":
    sys.exit(main())
